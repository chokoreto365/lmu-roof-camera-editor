    internal static class CamFile
    {
        public static string F(double value) { return value.ToString("0.000000", CultureInfo.InvariantCulture); }

        public static CamProfile Load(string path, string id)
        {
            CamProfile p = CamProfile.Default(id);
            if (!File.Exists(path)) return p;
            string text = File.ReadAllText(path);
            Match match = Regex.Match(text, @"LocalCam=TVCOCKPIT\s*\{(?<body>.*?)\}", RegexOptions.IgnoreCase | RegexOptions.Singleline);
            Match onboard = Regex.Match(text, @"LocalCam=ONBOARD000\s*\{(?<body>.*?)\}", RegexOptions.IgnoreCase | RegexOptions.Singleline);
            if (onboard.Success && (!match.Success || Regex.IsMatch(text, "CameraSlot=ONBOARD000", RegexOptions.IgnoreCase)))
            {
                p.Slot = "ONBOARD000";
                match = onboard;
            }
            else p.Slot = "TVCOCKPIT";
            if (!match.Success) return p;
            string body = match.Groups["body"].Value;
            Match pos = Regex.Match(body, @"PositionOffset=\(\s*(?<x>[-+0-9.eE]+)\s*,\s*(?<y>[-+0-9.eE]+)\s*,\s*(?<z>[-+0-9.eE]+)\s*\)", RegexOptions.IgnoreCase);
            if (pos.Success)
            {
                p.X = Number(pos.Groups["x"].Value, p.X);
                p.Y = Number(pos.Groups["y"].Value, p.Y);
                p.Z = Number(pos.Groups["z"].Value, p.Z);
            }
            Match ori = Regex.Match(body, @"OrientationOffset=\(\s*(?<pitch>[-+0-9.eE]+)", RegexOptions.IgnoreCase);
            if (ori.Success) p.Pitch = Number(ori.Groups["pitch"].Value, p.Pitch);
            Match clip = Regex.Match(body, @"ClipPlanes=\(\s*(?<near>[-+0-9.eE]+)", RegexOptions.IgnoreCase);
            if (clip.Success) p.NearClip = Number(clip.Groups["near"].Value, p.NearClip);
            p.IncludeNose = Regex.IsMatch(text, @"LocalCam=NOSE", RegexOptions.IgnoreCase);
            return p;
        }

        private static double Number(string text, double fallback)
        {
            double value;
            return Double.TryParse(text, NumberStyles.Float, CultureInfo.InvariantCulture, out value) ? value : fallback;
        }

        public static string Build(CamProfile p)
        {
            StringBuilder text = new StringBuilder();
            text.AppendLine("// Generated by LMU Roof Camera Studio. Original files are backed up before modification.");
            text.AppendLine("// Metres / radians. Reload the track session after saving; this is not a live game preview.");
            string slot = p.Slot == "ONBOARD000" ? "ONBOARD000" : "TVCOCKPIT";
            text.AppendLine("// CameraSlot=" + slot);
            Block(text, slot, p);
            if (p.IncludeNose)
            {
                text.AppendLine();
                text.AppendLine("// Optional NOSE override; some cars may not draw bodywork in this view.");
                Block(text, "NOSE", p);
            }
            return text.ToString();
        }

        private static void Block(StringBuilder text, string name, CamProfile p)
        {
            text.AppendLine("LocalCam=" + name);
            text.AppendLine("{");
            text.AppendLine("  Fov=(74.000000, 45.000000)");
            text.AppendLine("  Clear=TRUE");
            text.AppendLine("  Color=(0, 0, 0)");
            text.AppendLine("  ClipPlanes=(" + F(p.NearClip) + ", 1500.000000)");
            text.AppendLine("  LODMultiplier=(1.000000)");
            text.AppendLine("  MipmapLODBias=(0.000000)");
            text.AppendLine("  Size=(1.000000, 1.000000)");
            text.AppendLine("  Center=(0.500000, 0.500000)");
            text.AppendLine("  Flags1=(0)");
            text.AppendLine("  Flags2=(0)");
            text.AppendLine("  RadiusLimits=(0.000000, 0.000000)");
            text.AppendLine("  OrientationRate=(90.000000, 90.000000, 90.000000)");
            text.AppendLine("  PositionOffset=(" + F(p.X) + ", " + F(p.Y) + ", " + F(p.Z) + ")");
            text.AppendLine("  OrientationOffset=(" + F(p.Pitch) + ", 0.000000, 0.000000)");
            text.AppendLine("  Radius=(0.000000)");
            text.AppendLine("}");
        }
    }

