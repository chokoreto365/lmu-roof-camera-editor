        public static IEnumerable<string> DetectRoots()
        {
            HashSet<string> steam = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            string[] keys = { @"HKEY_CURRENT_USER\Software\Valve\Steam", @"HKEY_LOCAL_MACHINE\SOFTWARE\WOW6432Node\Valve\Steam", @"HKEY_LOCAL_MACHINE\SOFTWARE\Valve\Steam" };
            foreach (string key in keys)
                foreach (string name in new[] { "SteamPath", "InstallPath" })
                {
                    object value = Registry.GetValue(key, name, null);
                    if (value != null) steam.Add(value.ToString());
                }
            steam.Add(Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.ProgramFilesX86), "Steam"));
            foreach (string root in steam.ToList())
            {
                string libraries = Path.Combine(root, @"steamapps\libraryfolders.vdf");
                if (File.Exists(libraries))
                    foreach (Match match in Regex.Matches(File.ReadAllText(libraries), "\\\"path\\\"\\s*\\\"([^\\\"]+)\\\""))
                        steam.Add(match.Groups[1].Value.Replace("\\\\", "\\"));
            }
            foreach (string root in steam) yield return Path.Combine(root, @"steamapps\common\Le Mans Ultimate");
        }
    }

    internal sealed class Backups
    {
        private readonly string root;
        public Backups(string root) { this.root = root; }

        private string DirectoryFor(string game)
        {
            string normalized = Path.GetFullPath(game).TrimEnd('\\').ToUpperInvariant();
            byte[] hash = SHA256.Create().ComputeHash(Encoding.UTF8.GetBytes(normalized));
            return Path.Combine(root, String.Concat(hash.Take(12).Select(b => b.ToString("x2"))));
        }

        public void Save(string game, string relative)
        {
            string dir = DirectoryFor(game);
            string manifest = Path.Combine(dir, "manifest.txt");
            Directory.CreateDirectory(dir);
            if (File.Exists(manifest))
                foreach (string line in File.ReadLines(manifest))
                {
                    string[] parts = line.Split('|');
                    if (parts.Length == 2 && String.Equals(parts[1], relative, StringComparison.OrdinalIgnoreCase)) return;
                }
            string source = Path.Combine(game, relative);
            bool existed = File.Exists(source);
            if (existed)
            {
                string destination = Path.Combine(dir, "files", relative);
                Directory.CreateDirectory(Path.GetDirectoryName(destination));
                File.Copy(source, destination, true);
            }
            File.AppendAllText(manifest, (existed ? "1|" : "0|") + relative + Environment.NewLine, new UTF8Encoding(false));
        }

        public int Restore(string game)
        {
            string dir = DirectoryFor(game);
            string manifest = Path.Combine(dir, "manifest.txt");
            if (!File.Exists(manifest)) return 0;
            int count = 0;
            foreach (string line in File.ReadAllLines(manifest))
            {
                string[] parts = line.Split('|');
                if (parts.Length != 2) continue;
                string target = Path.Combine(game, parts[1]);
                if (parts[0] == "1")
                {
                    byte[] data = File.ReadAllBytes(Path.Combine(dir, "files", parts[1]));
                    AtomicWrite(target, data);
                }
                else if (File.Exists(target)) File.Delete(target);
                count++;
            }
            Directory.Delete(dir, true);
            return count;
        }

        public static void AtomicWrite(string path, byte[] data)
        {
            Directory.CreateDirectory(Path.GetDirectoryName(path));
            string temp = path + ".camstudio-tmp";
            File.WriteAllBytes(temp, data);
            if (File.Exists(path)) File.Replace(temp, path, null);
            else File.Move(temp, path);
        }

        public static void AtomicText(string path, string text) { AtomicWrite(path, new UTF8Encoding(false).GetBytes(text)); }
    }

    internal static class Storage
    {
        public static string SettingsPath(string root) { return Path.Combine(root, @"UserData\player\Settings.JSON"); }
        public static string CamerasPath(string root) { return Path.Combine(root, @"UserData\Cameras"); }
        public static bool CustomEnabled(string root)
        {
            string text = File.ReadAllText(SettingsPath(root));
            Match match = Regex.Match(text, "\"Broadcast Custom Cameras\"\\s*:\\s*(true|false)", RegexOptions.IgnoreCase);
            if (!match.Success) throw new InvalidDataException("Settings.JSON 中找不到 Broadcast Custom Cameras。 ");
            return match.Groups[1].Value.Equals("true", StringComparison.OrdinalIgnoreCase);
        }

        public static void SaveVehicle(string root, Vehicle vehicle, bool gameRunning, Backups backups)
        {
            const string settingsRelative = @"UserData\player\Settings.JSON";
            if (!CustomEnabled(root))
            {
                if (gameRunning) throw new InvalidOperationException("首次启用需要关闭游戏一次。之后日常微调可在游戏运行时保存 CAM。 ");
                backups.Save(root, settingsRelative);
                string text = File.ReadAllText(SettingsPath(root));
                text = Regex.Replace(text, "(\"Broadcast Custom Cameras\"\\s*:\\s*)(true|false)", "${1}true", RegexOptions.IgnoreCase);
                Backups.AtomicText(SettingsPath(root), text);
            }
            string relative = @"UserData\Cameras\" + vehicle.Id + ".CAM";
            backups.Save(root, relative);
            Backups.AtomicText(Path.Combine(root, relative), CamFile.Build(vehicle.Profile));
        }
    }

    internal sealed class CameraPreview : Control
    {
        public bool TopView;
        public CamProfile Profile;
        public event EventHandler CameraMoved;
        private bool dragging;
        private const double PixelsPerMeter = 100.0;

        public CameraPreview()
        {
            DoubleBuffered = true;
            BackColor = Color.FromArgb(20, 26, 34);
            ForeColor = Color.White;
        }

        protected override void OnPaint(PaintEventArgs e)
        {
            base.OnPaint(e);
            Graphics g = e.Graphics;
            g.SmoothingMode = System.Drawing.Drawing2D.SmoothingMode.AntiAlias;
            using (Font font = new Font("Microsoft YaHei UI", 9F))
            {
                g.DrawString(TopView ? "俯视：拖动相机调 X / Z" : "侧视：拖动相机调 Z / Y", font, Brushes.White, 10, 8);
                g.DrawString("示意图，不是游戏实时画面", font, Brushes.LightGray, 10, 28);
            }
            if (Profile == null) return;
            float ox = Width / 2.0f;
            float oy = Height / 2.0f + 35;
            using (Pen body = new Pen(Color.FromArgb(80, 170, 240), 3F))
            using (Brush fill = new SolidBrush(Color.FromArgb(45, 90, 130)))
            using (Pen grid = new Pen(Color.FromArgb(55, 65, 75), 1F))
            {
                for (int x = 0; x < Width; x += 25) g.DrawLine(grid, x, 50, x, Height);
                for (int y = 50; y < Height; y += 25) g.DrawLine(grid, 0, y, Width, y);
                if (TopView)
                {
                    RectangleF car = new RectangleF(ox - 42, oy - 105, 84, 210);
                    g.FillRectangle(fill, car);
                    g.DrawRectangle(body, car.X, car.Y, car.Width, car.Height);
                    g.DrawLine(body, ox - 42, oy - 50, ox + 42, oy - 50);
                    g.DrawString("车头", Font, Brushes.LightGray, ox - 18, oy - 132);
                }
                else
                {
                    RectangleF car = new RectangleF(ox - 130, oy - 24, 260, 55);
                    g.FillRectangle(fill, car);
                    g.DrawRectangle(body, car.X, car.Y, car.Width, car.Height);
                    g.DrawEllipse(body, ox - 88, oy + 15, 38, 38);
                    g.DrawEllipse(body, ox + 50, oy + 15, 38, 38);
                    g.DrawString("前", Font, Brushes.LightGray, ox + 132, oy - 20);
                }
            }
            PointF camera = CameraPoint();
            using (Brush cameraBrush = new SolidBrush(Color.Orange))
            using (Pen direction = new Pen(Color.Orange, 2F))
            {
                g.FillEllipse(cameraBrush, camera.X - 8, camera.Y - 8, 16, 16);
                if (TopView)
                {
                    g.DrawLine(direction, camera.X, camera.Y, camera.X, camera.Y - 70);
                    g.DrawString("Z " + CamFile.F(Profile.Z) + " m   X " + CamFile.F(Profile.X) + " m", Font, Brushes.Orange, 10, Height - 28);
                }
                else
                {
                    float dx = (float)(Math.Cos(Profile.Pitch) * 80.0);
                    float dy = (float)(-Math.Sin(Profile.Pitch) * 80.0);
                    g.DrawLine(direction, camera.X, camera.Y, camera.X + dx, camera.Y + dy);
                    g.DrawString("Y " + CamFile.F(Profile.Y) + " m   Z " + CamFile.F(Profile.Z) + " m", Font, Brushes.Orange, 10, Height - 28);
                }
            }
        }

        private PointF CameraPoint()
        {
            float ox = Width / 2.0f;
            float oy = Height / 2.0f + 35;
            PointF point = TopView
                ? new PointF((float)(ox + Profile.X * PixelsPerMeter), (float)(oy + Profile.Z * PixelsPerMeter))
                : new PointF((float)(ox - Profile.Z * PixelsPerMeter), (float)(oy - Profile.Y * PixelsPerMeter));
            point.X = Math.Max(18, Math.Min(Width - 18, point.X));
            point.Y = Math.Max(65, Math.Min(Height - 38, point.Y));
            return point;
        }

        protected override void OnMouseDown(MouseEventArgs e)
        {
            base.OnMouseDown(e);
            if (Profile == null || e.Button != MouseButtons.Left) return;
            PointF camera = CameraPoint();
            if (Math.Abs(e.X - camera.X) < 22 && Math.Abs(e.Y - camera.Y) < 22)
            {
                dragging = true;
                Cursor = Cursors.Hand;
            }
        }

        protected override void OnMouseMove(MouseEventArgs e)
        {
            base.OnMouseMove(e);
            if (!dragging || Profile == null) return;
            float ox = Width / 2.0f;
            float oy = Height / 2.0f + 35;
            if (TopView)
            {
                Profile.X = Clamp((e.X - ox) / PixelsPerMeter, -2, 2);
                Profile.Z = Clamp((e.Y - oy) / PixelsPerMeter, -5, 5);
            }
            else
            {
                Profile.Z = Clamp((ox - e.X) / PixelsPerMeter, -5, 5);
                Profile.Y = Clamp((oy - e.Y) / PixelsPerMeter, -0.5, 2);
            }
            Invalidate();
            if (CameraMoved != null) CameraMoved(this, EventArgs.Empty);
        }

        protected override void OnMouseUp(MouseEventArgs e)
        {
            base.OnMouseUp(e);
            dragging = false;
            Cursor = Cursors.Default;
        }

        private static double Clamp(double value, double min, double max) { return Math.Max(min, Math.Min(max, value)); }
    }

