        private void AddNumber(Control parent, string text, NumericUpDown box, int left, int top, int min, int max)
        {
            Label label = new Label { Text = text, Left = left, Top = top + 4, Width = 68 };
            box.SetBounds(left + 70, top, 260, 28);
            box.Minimum = min;
            box.Maximum = max;
            box.DecimalPlaces = 1;
            box.Increment = text == "俯仰" ? 0.5M : 1M;
            box.ValueChanged += EditorChanged;
            parent.Controls.AddRange(new Control[] { label, box });
        }

        private void AutoDetect()
        {
            foreach (string candidate in Discovery.DetectRoots())
                if (Discovery.ValidRoot(candidate)) { rootText.Text = candidate; Scan(); return; }
            Log("未自动找到游戏，请手动选择 LMU 根目录。 ");
        }

        private void Browse()
        {
            using (FolderBrowserDialog dialog = new FolderBrowserDialog())
            {
                dialog.Description = "选择包含 UserData 的 Le Mans Ultimate 目录";
                if (Discovery.ValidRoot(rootText.Text)) dialog.SelectedPath = rootText.Text;
                if (dialog.ShowDialog(this) == DialogResult.OK) { rootText.Text = dialog.SelectedPath; Scan(); }
            }
        }

        private void Scan()
        {
            if (!Discovery.ValidRoot(rootText.Text))
            {
                MessageBox.Show(this, "目录无效，需要找到 Settings.JSON 和 vehicle_settings.json。", "无法扫描");
                return;
            }
            try
            {
                vehicles.Clear();
                list.Items.Clear();
                string dir = Storage.CamerasPath(rootText.Text);
                foreach (string id in Discovery.VehicleIds(rootText.Text))
                {
                    string path = Path.Combine(dir, id + ".CAM");
                    Vehicle vehicle = new Vehicle { Id = id, Name = Discovery.Friendly(id), FilePath = path, Profile = CamFile.Load(path, id) };
                    vehicles.Add(vehicle);
                    ListViewItem row = new ListViewItem(vehicle.Name);
                    row.SubItems.Add(File.Exists(path) ? "已有" : "未建");
                    row.Tag = vehicle;
                    list.Items.Add(row);
                }
                if (list.Items.Count > 0) list.Items[0].Selected = true;
                Log("识别到 " + vehicles.Count + " 个车辆配置；已读取现有 CAM 参数。 ");
                UpdateGameStatus();
            }
            catch (Exception ex) { Error(ex); }
        }

        private Vehicle Selected()
        {
            return list.SelectedItems.Count == 0 ? null : list.SelectedItems[0].Tag as Vehicle;
        }

        private void ShowSelected()
        {
            Vehicle vehicle = Selected();
            if (vehicle == null) return;
            selectedLabel.Text = vehicle.Name + Environment.NewLine + vehicle.Id + ".CAM";
            side.Profile = vehicle.Profile;
            top.Profile = vehicle.Profile;
            LoadEditor(vehicle.Profile);
            side.Invalidate();
            top.Invalidate();
        }

        private void LoadEditor(CamProfile p)
        {
            loading = true;
            try
            {
                xBox.Value = Clamp((decimal)(p.X * 100), xBox.Minimum, xBox.Maximum);
                yBox.Value = Clamp((decimal)(p.Y * 100), yBox.Minimum, yBox.Maximum);
                zBox.Value = Clamp((decimal)(p.Z * 100), zBox.Minimum, zBox.Maximum);
                pitchBox.Value = Clamp((decimal)(p.Pitch * 180 / Math.PI), pitchBox.Minimum, pitchBox.Maximum);
                noseCheck.Checked = p.IncludeNose;
                slotBox.SelectedIndex = p.Slot == "ONBOARD000" ? 1 : 0;
            }
            finally { loading = false; }
        }

        private static decimal Clamp(decimal value, decimal min, decimal max) { return Math.Max(min, Math.Min(max, value)); }

        private void EditorChanged(object sender, EventArgs e)
        {
            if (loading) return;
            Vehicle vehicle = Selected();
            if (vehicle == null) return;
            vehicle.Profile.X = (double)xBox.Value / 100;
            vehicle.Profile.Y = (double)yBox.Value / 100;
            vehicle.Profile.Z = (double)zBox.Value / 100;
            vehicle.Profile.Pitch = (double)pitchBox.Value * Math.PI / 180;
            vehicle.Profile.IncludeNose = noseCheck.Checked;
            vehicle.Profile.Slot = slotBox.SelectedIndex == 1 ? "ONBOARD000" : "TVCOCKPIT";
            MarkDirty(vehicle);
            side.Invalidate();
            top.Invalidate();
        }

        private void PreviewMoved(object sender, EventArgs e)
        {
            Vehicle vehicle = Selected();
            if (vehicle == null) return;
            LoadEditor(vehicle.Profile);
            MarkDirty(vehicle);
        }

        private void MarkDirty(Vehicle vehicle)
        {
            vehicle.Dirty = true;
            foreach (ListViewItem row in list.Items)
                if (Object.ReferenceEquals(row.Tag, vehicle)) row.SubItems[1].Text = "未保存";
        }

        private void SaveOne()
        {
            Vehicle vehicle = Selected();
            if (vehicle == null || !Discovery.ValidRoot(rootText.Text)) return;
            try
            {
                Storage.SaveVehicle(rootText.Text, vehicle, IsGameRunning(), backups);
                vehicle.Dirty = false;
                RefreshRow(vehicle);
                Log("已保存 " + vehicle.Id + ".CAM。回游戏重新进入或重启赛道会话后生效。 ");
            }
            catch (Exception ex) { Error(ex); }
        }

        private void SaveAll()
        {
            if (vehicles.Count == 0) return;
            string message = "将写入 " + vehicles.Count + " 份车辆 CAM。";
            if (!Storage.CustomEnabled(rootText.Text)) message += "\n首次启用需要当前已关闭游戏，并会修改一次 Settings.JSON。";
            message += "\n\n原文件会自动备份。是否继续？";
            if (MessageBox.Show(this, message, "写入全部车辆", MessageBoxButtons.YesNo, MessageBoxIcon.Question) != DialogResult.Yes) return;
            try
            {
                bool running = IsGameRunning();
                foreach (Vehicle vehicle in vehicles)
                {
                    Storage.SaveVehicle(rootText.Text, vehicle, running, backups);
                    vehicle.Dirty = false;
                    RefreshRow(vehicle);
                }
                Log("全部写入完成。游戏运行时保存的 CAM 仍需重进赛道会话加载。 ");
            }
            catch (Exception ex) { Error(ex); }
        }

        private void RefreshRow(Vehicle vehicle)
        {
            foreach (ListViewItem row in list.Items)
                if (Object.ReferenceEquals(row.Tag, vehicle)) row.SubItems[1].Text = File.Exists(vehicle.FilePath) ? "已保存" : "未建";
        }

        private void ResetSelected()
        {
            Vehicle vehicle = Selected();
            if (vehicle == null) return;
            vehicle.Profile = CamProfile.Default(vehicle.Id);
            side.Profile = vehicle.Profile;
            top.Profile = vehicle.Profile;
            LoadEditor(vehicle.Profile);
            MarkDirty(vehicle);
            side.Invalidate();
            top.Invalidate();
        }

        private void ReloadSelected()
        {
            Vehicle vehicle = Selected();
            if (vehicle == null) return;
            vehicle.Profile = CamFile.Load(vehicle.FilePath, vehicle.Id);
            vehicle.Dirty = false;
            ShowSelected();
            RefreshRow(vehicle);
            Log("已从磁盘重新读取当前车辆 CAM。 ");
        }

        private void Restore()
        {
            if (IsGameRunning()) { MessageBox.Show(this, "恢复可能涉及 Settings.JSON，请先关闭游戏。", "需要关闭游戏"); return; }
            if (MessageBox.Show(this, "恢复本工具第一次修改前备份的 Settings.JSON 和 CAM；本工具新建的文件会删除。是否继续？", "恢复原始文件", MessageBoxButtons.YesNo, MessageBoxIcon.Warning) != DialogResult.Yes) return;
            try
            {
                int count = backups.Restore(rootText.Text);
                Scan();
                Log("恢复完成，处理 " + count + " 个文件。 ");
            }
            catch (Exception ex) { Error(ex); }
        }

        private void OpenFolder()
        {
            string dir = Storage.CamerasPath(rootText.Text);
            if (Directory.Exists(dir)) Process.Start("explorer.exe", "\"" + dir + "\"");
        }

        private static bool IsGameRunning() { return Process.GetProcessesByName("Le Mans Ultimate").Length > 0; }

        private void UpdateGameStatus()
        {
            if (!Discovery.ValidRoot(rootText.Text)) { gameLabel.Text = "等待有效游戏目录"; return; }
            try
            {
                bool running = IsGameRunning();
                bool enabled = Storage.CustomEnabled(rootText.Text);
                gameLabel.ForeColor = running ? Color.DarkOrange : Color.DarkGreen;
                gameLabel.Text = running ? "LMU 运行中：可保存 CAM，重进会话加载" : "LMU 已关闭";
                if (running && !enabled) gameLabel.Text = "LMU 运行中；首次启用需关闭一次";
            }
            catch { gameLabel.Text = "无法读取设置状态"; }
        }

        private void Error(Exception ex)
        {
            Log("错误：" + ex.Message);
            MessageBox.Show(this, ex.Message, "操作未完成", MessageBoxButtons.OK, MessageBoxIcon.Warning);
        }

        private void Log(string text) { logBox.AppendText(DateTime.Now.ToString("HH:mm:ss") + "  " + text + Environment.NewLine); }
    }

    internal static class SelfTest
    {
        private static void Assert(bool condition, string message) { if (!condition) throw new Exception(message); }

        public static int Run(string logPath)
        {
            string baseDir = String.IsNullOrEmpty(logPath) ? Path.GetTempPath() : Path.GetDirectoryName(logPath);
            string root = Path.Combine(baseDir, "camstudio-test-" + Guid.NewGuid().ToString("N"));
            string game = Path.Combine(root, "game");
            try
            {
                string player = Path.Combine(game, @"UserData\player");
                string cameras = Path.Combine(game, @"UserData\Cameras");
                Directory.CreateDirectory(player);
                Directory.CreateDirectory(cameras);
                File.WriteAllText(Storage.SettingsPath(game), "{\n  \"Broadcast Custom Cameras\": false,\n  \"Other\": 123\n}");
                File.WriteAllText(Path.Combine(player, "vehicle_settings.json"), "[{\"name\":\"FMGT3\"},{\"name\":\"720SEVO_GT3\"},{\"name\":\"F296GT3\"}]");
                string oldCam = Path.Combine(cameras, "FORD_MUSTANG_GT3.CAM");
                File.WriteAllText(oldCam, "ORIGINAL USER CAMERA");
                List<string> ids = Discovery.VehicleIds(game);
                Assert(ids.Count == 3 && ids.Contains("FORD_MUSTANG_GT3"), "vehicle discovery / Mustang alias");
                Backups backups = new Backups(Path.Combine(root, "backups"));
                Vehicle mustang = new Vehicle { Id = "FORD_MUSTANG_GT3", Profile = CamProfile.Default("FORD_MUSTANG_GT3") };
                Storage.SaveVehicle(game, mustang, false, backups);
                Assert(Storage.CustomEnabled(game), "first-run enable");
                string settingsAfterEnable = File.ReadAllText(Storage.SettingsPath(game));
                mustang.Profile.Y = 0.70;
                Storage.SaveVehicle(game, mustang, true, backups);
                Assert(File.ReadAllText(Storage.SettingsPath(game)) == settingsAfterEnable, "running save must not touch Settings");
                Assert(File.ReadAllText(oldCam).Contains("0.700000"), "running CAM save");

                Vehicle mclaren = new Vehicle { Id = "720SEVO_GT3", Profile = CamProfile.Default("720SEVO_GT3") };
                Storage.SaveVehicle(game, mclaren, true, backups);
                string mclarenText = File.ReadAllText(mclaren.FilePath ?? Path.Combine(cameras, "720SEVO_GT3.CAM"));
                Assert(mclarenText.Contains("LocalCam=TVCOCKPIT"), "default slot");
                Assert(mclarenText.Contains("PositionOffset=(0.000000, 0.900000, 0.650000)"), "default offset");
                Assert(mclarenText.Contains("ClipPlanes=(0.050000, 1500.000000)"), "default near clip");
                CamProfile loadedMclaren = CamFile.Load(Path.Combine(cameras, "720SEVO_GT3.CAM"), "720SEVO_GT3");
                Assert(loadedMclaren.Slot == "TVCOCKPIT" && loadedMclaren.Y == 0.9, "slot reload");

                File.WriteAllText(Storage.SettingsPath(game), settingsAfterEnable.Replace("\"Broadcast Custom Cameras\": true", "\"Broadcast Custom Cameras\": false"));
                bool blocked = false;
                try { Storage.SaveVehicle(game, new Vehicle { Id = "F296GT3", Profile = CamProfile.Default("F296GT3") }, true, backups); }
                catch (InvalidOperationException) { blocked = true; }
                Assert(blocked && !File.Exists(Path.Combine(cameras, "F296GT3.CAM")), "first enable while running must block");

                int restored = backups.Restore(game);
                Assert(restored >= 3, "restore count");
                Assert(File.ReadAllText(oldCam) == "ORIGINAL USER CAMERA", "original CAM restore");
                Assert(!File.Exists(Path.Combine(cameras, "720SEVO_GT3.CAM")), "new CAM removal");
                Assert(!Storage.CustomEnabled(game), "settings restore");
                if (!String.IsNullOrEmpty(logPath)) File.WriteAllText(logPath, "PASS: discovery, first enable, game-running CAM-only save, first-run block, default profile, backup and restore.");
                return 0;
            }
            catch (Exception ex)
            {
                if (!String.IsNullOrEmpty(logPath)) File.WriteAllText(logPath, ex.ToString());
                return 1;
            }
            finally { try { Directory.Delete(root, true); } catch { } }
        }
    }

    internal static class Program
    {
        [STAThread]
        private static int Main(string[] args)
        {
            if (args.Length > 0 && args[0] == "--self-test") return SelfTest.Run(args.Length > 1 ? args[1] : null);
            if (args.Length > 2 && args[0] == "--scan")
            {
                try { File.WriteAllLines(args[2], Discovery.VehicleIds(args[1]), new UTF8Encoding(false)); return 0; }
                catch { return 1; }
            }
            Application.EnableVisualStyles();
            Application.SetCompatibleTextRenderingDefault(false);
            Application.Run(new MainForm());
            return 0;
        }
